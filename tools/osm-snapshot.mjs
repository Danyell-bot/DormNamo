/* ==========================================================
   osm-snapshot.mjs - save nearby places for every pinned dorm into
   js/nearby-snapshot.js, so the listing dialog shows them instantly
   instead of waiting on the free (slow, often busy) Overpass servers.
   Usage: npm run nearby            (dorms without a fresh snapshot)
          npm run nearby -- --all   (refresh every pinned dorm)
   Run it after adding pins with pin.html. No key needed.
   OpenStreetMap data is ODbL: the site shows the required attribution.
   ========================================================== */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
import Core from "../js/nearby-core.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "js", "nearby-snapshot.js");
const SERVERS = [
  "https://overpass-api.de/api/interpreter",
  "https://overpass.kumi.systems/api/interpreter",
  "https://maps.mail.ru/osm/tools/overpass/api/interpreter",
];
const MAX_AGE_DAYS = 30,
  all = process.argv.includes("--all");

// load listings + pins exactly as the browser does
const ctx = { localStorage: { getItem: () => null } };
ctx.window = ctx;
ctx.self = ctx;
vm.createContext(ctx);
for (const f of ["data", "utils", "pins", "nearby-core", "maps"])
  vm.runInContext(fs.readFileSync(path.join(ROOT, "js", f + ".js"), "utf8"), ctx, { filename: f });
const houses = vm.runInContext("HOUSES.filter(function (h) { return h.lat != null && h.lng != null; })", ctx);
let snap = {};
if (fs.existsSync(OUT)) {
  const c2 = {};
  vm.createContext(c2);
  vm.runInContext(fs.readFileSync(OUT, "utf8"), c2);
  snap = c2.NEARBY_SNAPSHOT || {};
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function overpass(query) {
  for (let round = 0; round < 3; round++) {
    for (const url of SERVERS) {
      try {
        const r = await fetch(url, {
          method: "POST",
          body: "data=" + encodeURIComponent(query),
          headers: {
            "Content-Type": "application/x-www-form-urlencoded",
            "User-Agent": "DormNamo-snapshot/1.0",
          },
          signal: AbortSignal.timeout(60000),
        });
        if (r.ok) return await r.json();
        console.log("   " + new URL(url).host + " busy (" + r.status + ")");
      } catch (e) {
        console.log("   " + new URL(url).host + " " + e.message);
      }
    }
    await sleep(10000 * (round + 1));
  }
  throw new Error("all Overpass servers busy, try again later");
}

let done = 0,
  failed = 0;
for (const h of houses) {
  const old = snap[h.id];
  const fresh =
    old &&
    Math.abs(old.lat - h.lat) < 1e-6 &&
    Math.abs(old.lng - h.lng) < 1e-6 &&
    (Date.now() - Date.parse(old.fetchedAt)) / 864e5 < MAX_AGE_DAYS;
  if (fresh && !all) {
    console.log("skip  #" + h.id + " " + h.n);
    continue;
  }
  console.log("fetch #" + h.id + " " + h.n + " …");
  try {
    const origin = { lat: h.lat, lng: h.lng };
    const res = Core.osmResult((await overpass(Core.osmQuery(origin))).elements, origin);
    snap[h.id] = { lat: h.lat, lng: h.lng, fetchedAt: new Date().toISOString(), ...res };
    console.log(
      "      " + Core.CATEGORIES.map((c) => c.key + ":" + res.categories[c.key].places.length).join(" "),
    );
    done++;
    await sleep(2000); // be polite to the free servers
  } catch (e) {
    console.error("      failed: " + e.message);
    failed++;
  }
}
// drop snapshots of dorms that are no longer pinned
const pinned = new Set(houses.map((h) => String(h.id)));
Object.keys(snap).forEach((id) => {
  if (!pinned.has(id)) delete snap[id];
});
fs.writeFileSync(
  OUT,
  "/* Generated by tools/osm-snapshot.mjs (npm run nearby). Nearby places per pinned dorm.\n   Data © OpenStreetMap contributors, ODbL. Do not edit by hand. */\nvar NEARBY_SNAPSHOT = " +
    JSON.stringify(snap) +
    ";\n",
);
console.log(done + " updated, " + failed + " failed. Wrote js/nearby-snapshot.js");
if (failed) process.exitCode = 1;
