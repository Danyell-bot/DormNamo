/* make-config.mjs - write shared/js/app/config.js (browser settings) from .env
   Usage: npm run config
   shared/js/app/config.js is gitignored: the browser key is public once deployed, but it
   stays out of the repository and is protected by its HTTP referrer restriction. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { jsPath } from "./js-files.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
try {
  process.loadEnvFile(path.join(ROOT, ".env"));
} catch {
  /* use the real environment */
}

const cfg = {
  mapsBrowserKey: process.env.GOOGLE_MAPS_BROWSER_KEY || "",
  mapId: process.env.GOOGLE_MAPS_MAP_ID || "DEMO_MAP_ID",
  nearbyApiUrl: (process.env.NEARBY_API_URL || "").replace(/\/+$/, ""),
  // Nearby places from Google through the worker only when NEARBY_GOOGLE=on (the worker then needs
  // GOOGLE_MAPS_SERVER_KEY); otherwise the worker serves Namo only and nearby stays on OpenStreetMap.
  nearbyGoogle: process.env.NEARBY_GOOGLE === "on",
  // Namo wording by Google Gemini through the worker (POST /namo). Each student is still asked first.
  namoAI: process.env.NAMO_AI !== "off",
  // Supabase (database + logins). Only the browser-safe anon/publishable key; RLS protects the data.
  supabaseUrl: (process.env.SUPABASE_URL || "").replace(/\/+$/, "").replace(/\/rest\/v1$/, ""),
  supabaseKey: process.env.SUPABASE_ANON_KEY || process.env.SUPABASE_PUBLISHABLE_KEY || "",
};
if (/service_role|sb_secret_/.test(cfg.supabaseKey) || jwtRole(cfg.supabaseKey) === "service_role") {
  console.error("SUPABASE_ANON_KEY is a secret (service_role) key. Use the anon or publishable key.");
  process.exit(1);
}
function jwtRole(k) {
  try {
    return JSON.parse(Buffer.from(k.split(".")[1], "base64url").toString()).role;
  } catch {
    return "";
  }
}
const out =
  "/* Generated by tools/make-config.mjs from .env. Do not edit or commit. */\nvar DN_CONFIG = " +
  JSON.stringify(cfg, null, 2) +
  ";\n";
fs.writeFileSync(jsPath("config"), out);
console.log(
  "Wrote shared/js/app/config.js (browser key " +
    (cfg.mapsBrowserKey ? "set" : "MISSING") +
    ", nearby API " +
    (cfg.nearbyApiUrl || "MISSING") +
    ", Supabase " +
    (cfg.supabaseUrl && cfg.supabaseKey ? "set" : "MISSING") +
    ").",
);
